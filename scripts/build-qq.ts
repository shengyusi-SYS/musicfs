import { dirname, join, relative, resolve } from 'node:path';
import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';
import schema from '../plugins/qq/config.schema.json';
import { audioTagBuildOptions, audioTagLicenses, buildPlugin } from './build-plugin';

export async function generateQqUpstream() {
  const dependency = dirname(Bun.resolveSync('@yakult-green-tea/qq-music-api/package.json', resolve('plugins/qq')));
  const metadata = await Bun.file(join(dependency, 'package.json')).json() as { version: string };
  if (metadata.version !== '3.3.3') throw new Error('Revalidate the QQ private SDK adapter before upgrading its pinned dependency');
  const exports = [
    ['createSealedSessionResolver', 'serverless/sealedResolver.js'],
    ['deriveAndroidDevice', 'serverless/derivedDevice.js'],
    ['createSessionMusicuClient', 'services/recommend/sessionMusicu.js'],
    ['AUTH_REFRESH_EARLY_MS, AUTH_REFRESH_RETRY_MS', 'services/auth/sessionState.js'],
    ['createFetchTransport', 'transport/fetch.js'],
    ['refreshLoginCredential', 'services/auth/authenticatedReads.js'],
    ['credentialMusicId', 'services/auth/androidDevice.js'],
    ['QqApiError', 'protocol/errors.js'],
    ['StreamCdnSelector', 'services/auth/streamCdnSelector.js'],
    ['DAILY_SONGS', 'services/recommend/dailySongs.js'],
    ['recommendPlaylistsResult', 'services/recommend/recommendPlaylists.js'],
    ['apeFileFailureOf', 'protocol/qualityFile.js'],
    ['MUSIC_FILE_TYPES', 'services/auth/playback.js'],
    ['createAuthHttpClient', 'services/auth/httpClient.js'],
    ['cookieHeader, mergeCookieHeaders, normalizeSetCookies, seedCookieJar, updateCookieJar', 'services/auth/cookieJar.js'],
    ['createQrLoginService', 'services/auth/qrService.js'],
    ['QrLoginServiceError', 'services/auth/musicuProtocol.js'],
    ['createPtloginQrDriver', 'services/auth/qrDrivers.js'],
    ['CHECK_BUDGET_MS, capabilitiesFor, capturingQrSessionRepository, qrDeviceRepositoryFor, replayedRecord, replayQrSessionRepository', 'serverless/qrRuntime.js'],
    ['openQrState, sealQrState', 'serverless/sealedQrState.js'],
    ['qrKey', 'routes/operations/qrKey.js'],
    ['qrCreate', 'routes/operations/qrCreate.js'],
    ['qrCheck', 'routes/operations/qrCheck.js'],
    ['qrCancel', 'routes/operations/qrCancel.js'],
    ['loginStatus', 'routes/operations/loginStatus.js'],
    ['json as upstreamJson, failureResponse', 'serverless/response.js']
  ] as const;
  const upstream = [];
  for (const [name, file] of exports) {
    if (!await Bun.file(join(dependency, 'dist-esm/src', file)).exists()) throw new Error(`Pinned QQ SDK export disappeared: ${file}`);
    upstream.push(`export { ${name} } from ${JSON.stringify('./node_modules/@yakult-green-tea/qq-music-api/dist-esm/src/' + file)};`);
  }
  // Use the SDK's installed Axios instance, including its browser Fetch adapter.
  // No second dependency or Node HTTP transport is introduced into the plugin.
  const axiosDirectory = dirname(Bun.resolveSync('axios/package.json', dependency));
  const axiosMetadata = await Bun.file(join(axiosDirectory, 'package.json')).json() as { version: string };
  if (axiosMetadata.version !== '1.20.0') throw new Error('Revalidate the QQ auth transport before upgrading its pinned Axios dependency');
  const axiosRelative = relative(resolve('plugins/qq'), join(axiosDirectory, 'index.js')).split('\\').join('/');
  const axiosEntry = axiosRelative.startsWith('.') ? axiosRelative : './' + axiosRelative;
  upstream.push(`export { default as axios } from ${JSON.stringify(axiosEntry)};`);
  await Bun.write('plugins/qq/generated-upstream.mjs', upstream.join('\n') + '\n');
  const declarations = exports.map(([name, file]) => `export { ${name} } from ${JSON.stringify('./node_modules/@yakult-green-tea/qq-music-api/dist/src/' + file)};`);
  for (const [name, file] of [
    ['AuthHttpClient', 'services/auth/httpClient.js'],
    ['AuthSession, QrLoginChannel, QrSessionRepository', 'services/auth/qrTypes.js'],
    ['MusicuDescriptor', 'protocol/musicu.js'],
    ['OperationHandler, QrRouteService', 'routes/operations/types.js'],
    ['SealedQrPayloadV1', 'serverless/sealedQrState.js']
  ]) declarations.push(`export type { ${name} } from ${JSON.stringify('./node_modules/@yakult-green-tea/qq-music-api/dist/src/' + file)};`);
  declarations.push(`export { default as axios } from ${JSON.stringify(axiosEntry)};`);
  await Bun.write('plugins/qq/generated-upstream.d.mts', '// Matching declarations for the pinned SDK ESM author entry; generated by scripts/build-qq.ts.\n' + declarations.join('\n') + '\n');
  return { dependency, axiosDirectory };
}

export async function buildQq() {
  const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
  await Bun.write('plugins/qq/generated-config.mjs', standalone(ajv, ajv.compile(schema)));
  const { dependency, axiosDirectory } = await generateQqUpstream();
  await Bun.write('plugins/qq/LICENSE.txt', await Bun.file('plugins/sample/LICENSE.txt').text());
  const licenses = [];
  for (const [name, location] of [['@yakult-green-tea/qq-music-api 3.3.3', join(dependency, 'LICENSE')], ['Axios 1.20.0', join(axiosDirectory, 'LICENSE')], ['Zod 4.6.7', 'node_modules/zod/LICENSE'], ['Ajv 8.20.0', 'node_modules/ajv/LICENSE']]) {
    licenses.push(`${name}\n\n${await Bun.file(location!).text()}`);
  }
  let lookup = resolve('plugins/qq');
  for (const name of ['p-limit', 'yocto-queue']) {
    const root = dirname(Bun.resolveSync(name, lookup));
    const info = await Bun.file(join(root, 'package.json')).json() as { version: string };
    licenses.push(`${name} ${info.version}\n\n${await Bun.file(join(root, 'license')).text()}`); lookup = root;
  }
  licenses.push(...await audioTagLicenses());
  await Bun.write('plugins/qq/THIRD_PARTY_LICENSE.txt', licenses.join('\n\n---\n\n'));
  await Bun.write('plugins/qq/THIRD_PARTY_ATTRIBUTION.md', await Bun.file(join(dependency, 'ATTRIBUTION.md')).text());
  // The SDK logger reads process.env. Freeze its logging settings at author build time;
  // the installed bundle has no process global or host environment dependency.
  return buildPlugin('plugins/qq', 'dist/plugins/org.musicfs.qq.zip', { ...audioTagBuildOptions, define: { 'process.env': JSON.stringify({ LOG_LEVEL: 'error' }) } });
}
if (import.meta.main) console.log(`Built QQ development plugin (${(await buildQq()).byteLength} bytes)`);
